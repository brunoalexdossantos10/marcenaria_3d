import type { FurnitureCategory, FurnitureConfig, FurnitureType, Limits } from "./types.ts";

export interface CatalogVariant {
  id: FurnitureType;
  label: string;
  base: FurnitureType;
  category?: FurnitureCategory;
  defaults: Partial<FurnitureConfig>;
  limits?: Limits;
  description?: string;
  tags?: string[];
  installation?: "piso" | "parede" | "suspenso";
}

const preset = (
  id: string,
  label: string,
  base: FurnitureType,
  defaults: Partial<FurnitureConfig>,
  category?: FurnitureCategory,
  installation?: CatalogVariant["installation"],
): CatalogVariant => ({
  id,
  label,
  base,
  defaults,
  ...(category ? { category } : {}),
  ...(installation ? { installation } : {}),
});

